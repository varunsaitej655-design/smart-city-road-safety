// Helper to parse uploaded or raw CSV string into AccidentDatasetRecord[]
export function parseCsvDataset(csvText: string): AccidentDatasetRecord[] {
  const lines = csvText.trim().split('\n');
  if (lines.length < 2) return [];

  const records: AccidentDatasetRecord[] = [];

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    // Handle CSV line splitting taking care of quoted values
    const parts: string[] = [];
    let insideQuote = false;
    let current = '';

    for (let charIdx = 0; charIdx < line.length; charIdx++) {
      const char = line[charIdx];
      if (char === '"') {
        insideQuote = !insideQuote;
      } else if (char === ',' && !insideQuote) {
        parts.push(current.trim().replace(/^"|"$/g, ''));
        current = '';
      } else {
        current += char;
      }
    }
    parts.push(current.trim().replace(/^"|"$/g, ''));

    if (parts.length >= 10) {
      records.push({
        locationId: parts[0] || `LOC-IMP-${i}`,
        locationName: parts[1] || `Corridor ${i}`,
        state: parts[2] || 'India',
        highwayNumber: parts[3] || 'National Highway',
        hour: parseInt(parts[4], 10) || 12,
        dayOfWeek: parts[5] || 'Monday',
        isPeakHour: parts[6] === '1' || parts[6]?.toLowerCase() === 'true',
        weather: (parts[7] as any) || 'Clear',
        visibilityMeters: parseInt(parts[8], 10) || 2000,
        surfaceQuality: (parts[9] as any) || 'Dry Asphalt',
        potholeCount: parseInt(parts[10], 10) || 0,
        suddenDiversion: parts[11] === '1' || parts[11]?.toLowerCase() === 'true',
        speedBreakerCount: parseInt(parts[12], 10) || 0,
        trafficLevel: (parts[13] as any) || 'Medium',
        speedLimitKmh: parseInt(parts[14], 10) || 80,
        roadType: (parts[15] as any) || 'Highway',
        curvature: (parts[16] as any) || 'Straight',
        historicalAccidentsAnnual: parseInt(parts[17], 10) || 0,
        isBlackspot: parts[18] === '1' || parts[18]?.toLowerCase() === 'true',
        historicalFatalities: parseInt(parts[19], 10) || 0,
        coordinates: { x: 30 + ((i * 7) % 50), y: 25 + ((i * 11) % 60) },
      });
    }
  }

  return records;
}

